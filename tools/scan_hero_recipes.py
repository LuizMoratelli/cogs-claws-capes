"""Scan the server's mod jars and list the hero recipes the gating script rewrites.

  python tools/scan_hero_recipes.py   -> overrides/kubejs/server_scripts/generated/hero_targets.js + docs/references/data/hero_targets.json

A hero recipe is gated when its OUTPUT is an END item: an item of a hero namespace that no other recipe in any jar
uses as an ingredient (so ingots, circuits and other parts stay cheap; the suit / gadget / power item costs a Hero Core).
Tailoring recipes (palladium:suit_set_tailoring / item_tailoring) are always gated. Run after `build.py server`.
"""
import glob, json, re, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HERO_NS = ["fsang", "satsu_iron_man_addon", "powerborne", "pantheonsent", "gravecore"]
CRAFT = {"minecraft:crafting_shaped", "minecraft:crafting_shapeless"}
TAILOR = {"palladium:suit_set_tailoring", "palladium:item_tailoring"}
# Cosmetics, ordinary tools/ammo, colour variants and repair kits stay cheap: the gate is for powers, suits and gadgets.
NOT_GATED = re.compile(r"(^|_)(scarf|cape|jacket|trail|tri_polymer|fabric_mending|mending\d*|name_changer|changer|dampen|"
                       r"axe|hoe|pickaxe|shovel|sword|arrow|playing_card|pellet|wire|wires|ingot|nugget|block|plate|dye|"
                       r"cloth|fabric|thread|empty|pillar|paint|cure|archeology)(_|$|\d)")

def outputs(j):
    r = j.get("result") or j.get("results")
    if isinstance(r, str): return [r]
    if isinstance(r, dict):
        if "item" in r: return [r["item"]]
        return [v if isinstance(v, str) else v.get("item") for v in r.values()]
    return []

recipes = []
for jar in glob.glob(str(ROOT / "server" / "mods" / "*.jar")):
    z = zipfile.ZipFile(jar)
    for n in z.namelist():
        m = re.match(r"data/([^/]+)/recipes/(.+)\.json$", n)
        if not m: continue
        try: j = json.loads(z.read(n))
        except Exception: continue
        recipes.append((f"{m.group(1)}:{m.group(2)}", j))

ingredient_text = {}
for rid, j in recipes:
    body = dict(j); body.pop("result", None); body.pop("results", None)
    ingredient_text[rid] = json.dumps(body)
all_ing = "\n".join(ingredient_text.values())

craft, tailor = [], []
for rid, j in recipes:
    ns = rid.split(":")[0]
    if ns not in HERO_NS: continue
    t = j.get("type")
    if t in TAILOR:
        tailor.append(rid)
    elif t in CRAFT:
        outs = [o for o in outputs(j) if o]
        if outs and all(f'"{o}"' not in all_ing for o in outs) and not NOT_GATED.search(outs[0].split(":")[1].split("/")[-1]):
            craft.append({"id": rid, "type": t, "output": outs[0]})

craft.sort(key=lambda x: x["id"]); tailor.sort()
data = {"hero_namespaces": HERO_NS, "tailoring": tailor, "crafting_end_items": craft,
        "method": "tools/scan_hero_recipes.py over server/mods/*.jar"}
out = ROOT / "docs" / "references" / "data" / "hero_targets.json"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps(data, indent=1) + "\n")
js = ROOT / "overrides" / "kubejs" / "server_scripts" / "generated" / "hero_targets.js"
js.parent.mkdir(parents=True, exist_ok=True)
js.write_text("// GENERATED by tools/scan_hero_recipes.py - do not edit by hand.\n"
              f"global.HERO_TAILORING = {json.dumps(tailor)}\n"
              f"global.HERO_CRAFT_END_ITEMS = {json.dumps([c['id'] for c in craft])}\n")
print(f"scanned {len(recipes)} recipes: gating {len(tailor)} tailoring + {len(craft)} crafting end-items")
for c in craft[:400]: print("  ", c["id"], "->", c["output"])
